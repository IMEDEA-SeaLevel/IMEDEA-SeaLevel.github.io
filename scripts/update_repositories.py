#!/usr/bin/env python3
"""Write data/repositories.yml with the PUBLIC repositories of the organisation.

Private repositories are never listed, whatever token is used.
"""
import sys

from util import dump, env, get_json, load


def main():
    site = load("site.yml")
    org = site["github_org"]
    headers = {"Accept": "application/vnd.github+json"}
    token = env("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = "Bearer " + token

    repos, page = [], 1
    while True:
        batch = get_json(
            f"https://api.github.com/orgs/{org}/repos?type=public&per_page=100&page={page}",
            headers,
        )
        if not batch:
            break
        repos += batch
        if len(batch) < 100:
            break
        page += 1

    out = []
    for r in repos:
        # Explicit safety filter: only public repositories, never private ones.
        if r.get("private") is not False or r.get("visibility", "public") != "public":
            continue
        name = r["name"]
        if name.lower().endswith(".github.io") or name == ".github" or r.get("fork"):
            continue
        out.append(
            {
                "name": name,
                "description": r.get("description") or "",
                "url": r["html_url"],
                "homepage": r.get("homepage") or "",
                "language": r.get("language") or "",
                "stars": r.get("stargazers_count", 0),
                "forks": r.get("forks_count", 0),
                "license": (r.get("license") or {}).get("spdx_id") or "",
                "topics": r.get("topics") or [],
                "updated": (r.get("pushed_at") or r.get("updated_at") or "")[:10],
                "archived": bool(r.get("archived")),
            }
        )
    out.sort(key=lambda r: (r["archived"], -r["stars"], r["name"].lower()))
    changed = dump(
        "repositories.yml", out, "Generated by scripts/update_repositories.py — do not edit by hand."
    )
    print(f"{len(out)} public repositories ({'updated' if changed else 'no changes'})")


if __name__ == "__main__":
    sys.exit(main())
